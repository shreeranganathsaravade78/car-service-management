CREATE TABLE BOOKING_SERVICE (
  Booking_ID INT NOT NULL,
  Service_ID INT NOT NULL,
  Quantity   INT NOT NULL CHECK (Quantity > 0),
  Unit_Price DECIMAL(10,2) NOT NULL CHECK (Unit_Price >= 0), -- price charged at that time
  PRIMARY KEY (Booking_ID, Service_ID),
  FOREIGN KEY (Booking_ID) REFERENCES BOOKING(Booking_ID),
  FOREIGN KEY (Service_ID) REFERENCES SERVICE(Service_ID)
);

CREATE TABLE BOOKING_MECHANIC (
  Booking_ID       INT NOT NULL,
  Mechanic_ID      INT NOT NULL,
  Assigned_At      TIMESTAMP NOT NULL,
  Work_Description VARCHAR(255),
  Work_Status      VARCHAR(20) NOT NULL
      CHECK (Work_Status IN ('Not Started','In Progress','Completed')),
  PRIMARY KEY (Booking_ID, Mechanic_ID),
  FOREIGN KEY (Booking_ID)  REFERENCES BOOKING(Booking_ID),
  FOREIGN KEY (Mechanic_ID) REFERENCES MECHANIC(Mechanic_ID)
);

CREATE TABLE INVOICE (
  Invoice_ID      INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  Booking_ID      INT NOT NULL UNIQUE,            -- 1:1 with BOOKING
  Invoice_Date    DATE NOT NULL,
  Labor_Charge    DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (Labor_Charge >= 0),
  Tax_Amount      DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (Tax_Amount >= 0),
  Discount_Amount DECIMAL(10,2) NOT NULL DEFAULT 0 CHECK (Discount_Amount >= 0),
  Invoice_Status  VARCHAR(20) NOT NULL
      CHECK (Invoice_Status IN ('Unpaid','Partially Paid','Paid')),
  FOREIGN KEY (Booking_ID) REFERENCES BOOKING(Booking_ID)
);

CREATE TABLE PAYMENT (
  Payment_ID     INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  Invoice_ID     INT NOT NULL,
  Payment_Date   DATE NOT NULL,
  Amount         DECIMAL(10,2) NOT NULL CHECK (Amount > 0),
  Payment_Method VARCHAR(20) NOT NULL
      CHECK (Payment_Method IN ('Cash','UPI','Credit Card','Debit Card','Net Banking')),
  Payment_Status VARCHAR(20) NOT NULL
      CHECK (Payment_Status IN ('Success','Pending','Failed','Refunded')),
  FOREIGN KEY (Invoice_ID) REFERENCES INVOICE(Invoice_ID)
);

-- =========================================================
-- INDEXES FOR COMMON SEARCH / FILTER OPERATIONS
