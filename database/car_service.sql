-- Total_Amount is DERIVED (not stored): services + labor + tax - discount
CREATE VIEW Invoice_Total_View AS
SELECT i.Invoice_ID, i.Booking_ID, i.Invoice_Date,
       COALESCE(s.Services_Total,0)                                   AS Services_Total,
       i.Labor_Charge, i.Tax_Amount, i.Discount_Amount,
       COALESCE(s.Services_Total,0) + i.Labor_Charge + i.Tax_Amount - i.Discount_Amount AS Total_Amount,
       i.Invoice_Status
FROM INVOICE i
LEFT JOIN (SELECT Booking_ID, SUM(Quantity*Unit_Price) AS Services_Total
           FROM BOOKING_SERVICE GROUP BY Booking_ID) s
       ON s.Booking_ID = i.Booking_ID;

-- Shows invoice totals, successful payments and outstanding balances.
CREATE VIEW Invoice_Balance_View AS
SELECT
    v.Invoice_ID,
    v.Booking_ID,
    v.Total_Amount,
    COALESCE(p.Paid_Amount, 0.00) AS Paid_Amount,
    GREATEST(v.Total_Amount - COALESCE(p.Paid_Amount, 0.00), 0.00)
        AS Outstanding_Balance,
    v.Invoice_Status
FROM Invoice_Total_View v
LEFT JOIN (
    SELECT Invoice_ID, SUM(Amount) AS Paid_Amount
    FROM PAYMENT
    WHERE Payment_Status = 'Success'
    GROUP BY Invoice_ID
) p ON p.Invoice_ID = v.Invoice_ID;


