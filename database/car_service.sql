-- BUSINESS-RULE TRIGGERS
-- These triggers validate mechanic assignments and keep invoice
-- payment status synchronized with successful payment records.
-- =========================================================

DELIMITER $$

CREATE TRIGGER trg_booking_mechanic_active_insert
BEFORE INSERT ON BOOKING_MECHANIC
FOR EACH ROW
BEGIN
    DECLARE v_status VARCHAR(20);

    SELECT Employment_Status
      INTO v_status
      FROM MECHANIC
     WHERE Mechanic_ID = NEW.Mechanic_ID;

    IF v_status <> 'Active' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Only active mechanics can be assigned to a booking';
    END IF;
END$$

CREATE TRIGGER trg_booking_mechanic_active_update
BEFORE UPDATE ON BOOKING_MECHANIC
FOR EACH ROW
BEGIN
    DECLARE v_status VARCHAR(20);

    SELECT Employment_Status
      INTO v_status
      FROM MECHANIC
     WHERE Mechanic_ID = NEW.Mechanic_ID;

    IF v_status <> 'Active' THEN
        SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Only active mechanics can be assigned to a booking';
    END IF;
END$$

CREATE PROCEDURE Refresh_Invoice_Status(IN p_invoice_id INT)
BEGIN
    DECLARE v_total DECIMAL(12,2) DEFAULT 0.00;
    DECLARE v_paid DECIMAL(12,2) DEFAULT 0.00;

    SELECT Total_Amount
      INTO v_total
      FROM Invoice_Total_View
     WHERE Invoice_ID = p_invoice_id;

    SELECT COALESCE(SUM(Amount), 0.00)
      INTO v_paid
      FROM PAYMENT
     WHERE Invoice_ID = p_invoice_id
       AND Payment_Status = 'Success';

    UPDATE INVOICE
       SET Invoice_Status =
           CASE
             WHEN v_paid <= 0 THEN 'Unpaid'
             WHEN v_paid < v_total THEN 'Partially Paid'
             ELSE 'Paid'
           END
     WHERE Invoice_ID = p_invoice_id;
END$$

CREATE TRIGGER trg_payment_status_after_insert
AFTER INSERT ON PAYMENT
FOR EACH ROW
BEGIN
    CALL Refresh_Invoice_Status(NEW.Invoice_ID);
END$$

CREATE TRIGGER trg_payment_status_after_update
AFTER UPDATE ON PAYMENT
FOR EACH ROW
BEGIN
    CALL Refresh_Invoice_Status(OLD.Invoice_ID);

    IF NEW.Invoice_ID <> OLD.Invoice_ID THEN
        CALL Refresh_Invoice_Status(NEW.Invoice_ID);
    END IF;
END$$

CREATE TRIGGER trg_payment_status_after_delete
AFTER DELETE ON PAYMENT
FOR EACH ROW
BEGIN
    CALL Refresh_Invoice_Status(OLD.Invoice_ID);
END$$

DELIMITER ;

