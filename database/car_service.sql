DROP DATABASE IF EXISTS car_service;
CREATE DATABASE car_service
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_0900_ai_ci;

USE car_service;


CREATE TABLE CUSTOMER (
  Customer_ID   INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  First_Name    VARCHAR(50)  NOT NULL,
  Last_Name     VARCHAR(50)  NOT NULL,
  Phone         VARCHAR(15)  NOT NULL,
  Email         VARCHAR(100),
  House_Number  VARCHAR(20),
  Street        VARCHAR(100),
  Area          VARCHAR(100),
  City          VARCHAR(50),
  State         VARCHAR(50),
  Postal_Code   VARCHAR(10)
);

CREATE TABLE VEHICLE (
  Vehicle_ID          INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  Customer_ID         INT NOT NULL,
  Registration_Number VARCHAR(20) NOT NULL UNIQUE,
  Manufacturer        VARCHAR(50) NOT NULL,
  Model               VARCHAR(50) NOT NULL,
  Manufacturing_Year  INT CHECK (Manufacturing_Year IS NULL OR Manufacturing_Year >= 1886),
  Fuel_Type           VARCHAR(20) CHECK (Fuel_Type IN ('Petrol','Diesel','CNG','Electric','Hybrid')),
  FOREIGN KEY (Customer_ID) REFERENCES CUSTOMER(Customer_ID)
);

CREATE TABLE BOOKING (
  Booking_ID          INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  Vehicle_ID          INT NOT NULL,
  Booking_Date        DATE NOT NULL,
  Appointment_Date    DATE NOT NULL,
  Appointment_Time    TIME NOT NULL,
  Problem_Description VARCHAR(255),
  Booking_Status      VARCHAR(20) NOT NULL
      CHECK (Booking_Status IN ('Pending','Confirmed','In Progress','Completed','Cancelled')),
  FOREIGN KEY (Vehicle_ID) REFERENCES VEHICLE(Vehicle_ID),
  CHECK (Appointment_Date >= Booking_Date)
);

CREATE TABLE SERVICE (
  Service_ID         INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  Service_Name       VARCHAR(100) NOT NULL,
  Description        VARCHAR(255),
  Base_Price         DECIMAL(10,2) NOT NULL CHECK (Base_Price >= 0),
  Estimated_Duration INT CHECK (Estimated_Duration IS NULL OR Estimated_Duration > 0) -- minutes
);

CREATE TABLE MECHANIC (
  Mechanic_ID       INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  First_Name        VARCHAR(50) NOT NULL,
  Last_Name         VARCHAR(50) NOT NULL,
  Phone             VARCHAR(15),
  Specialization    VARCHAR(100),
  Employment_Status VARCHAR(20) NOT NULL
      CHECK (Employment_Status IN ('Active','On Leave','Resigned'))
);

-- =========================================================
-- APPLICATION AUTHENTICATION AND ROLE-BASED ACCESS
-- Password_Hash must contain a hash generated by the backend
-- (for example, bcrypt). Never store plain-text passwords.
-- Customer_ID / Mechanic_ID link a login to its profile.
-- Admin and Receptionist accounts can leave both fields NULL.
-- =========================================================

CREATE TABLE APP_USER (
  User_ID       INT AUTO_INCREMENT PRIMARY KEY,
  Username      VARCHAR(50) NOT NULL UNIQUE,
  Email         VARCHAR(100) NOT NULL UNIQUE,
  Password_Hash VARCHAR(255) NOT NULL,
  Customer_ID   INT UNIQUE,
  Mechanic_ID   INT UNIQUE,
  Account_Status VARCHAR(20) NOT NULL DEFAULT 'Active'
      CHECK (Account_Status IN ('Active','Disabled')),
  Created_At    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_app_user_customer
      FOREIGN KEY (Customer_ID) REFERENCES CUSTOMER(Customer_ID),
  CONSTRAINT fk_app_user_mechanic
      FOREIGN KEY (Mechanic_ID) REFERENCES MECHANIC(Mechanic_ID),
  CONSTRAINT chk_user_profile
      CHECK (Customer_ID IS NULL OR Mechanic_ID IS NULL)
);

CREATE TABLE ROLE (
  Role_ID   INT AUTO_INCREMENT PRIMARY KEY,
  Role_Name VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE USER_ROLE (
  User_ID INT NOT NULL,
  Role_ID INT NOT NULL,
  PRIMARY KEY (User_ID, Role_ID),
  CONSTRAINT fk_user_role_user
      FOREIGN KEY (User_ID) REFERENCES APP_USER(User_ID),
  CONSTRAINT fk_user_role_role
      FOREIGN KEY (Role_ID) REFERENCES ROLE(Role_ID)
);

